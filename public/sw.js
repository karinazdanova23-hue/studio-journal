// Минимальный service worker — нужен только для того, чтобы браузер предложил
// «Установить приложение» / «На главный экран». Ничего не кэширует специально:
// приложение целиком завязано на живые данные с сервера (сессия, задачи, календарь),
// и агрессивное кэширование тут принесло бы больше вреда (устаревшие данные), чем пользы.
self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Просто пропускаем запрос к сети как обычно — оффлайн-режим сознательно не реализован.
  event.respondWith(fetch(event.request));
});
